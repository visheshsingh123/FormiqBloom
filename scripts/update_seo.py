#!/usr/bin/env python3
"""Write static SEO metadata and crawl files. Optional maintenance tool; no build step."""
import argparse
import html
import json
from pathlib import Path
import re
from urllib.parse import urlsplit
from xml.etree import ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
START = '  <!-- SEO metadata: generated by scripts/update_seo.py from seo.config.json. -->'
END = '  <!-- / SEO metadata -->'


def business_graph(origin):
    org_id = origin + '/#organization'
    person_id = origin + '/#founder'
    address = {'@type': 'PostalAddress', 'addressLocality': 'Surat', 'addressRegion': 'Gujarat', 'addressCountry': 'IN'}
    return [
        {'@type': 'Organization', '@id': org_id, 'name': 'FormiqBloom', 'url': origin + '/',
         'description': 'A founder-led agency based in Surat offering responsive websites, managed hosting, and custom AI assistants.',
         'logo': {'@type': 'ImageObject', 'url': origin + '/Assets/logo.png', 'width': 2000, 'height': 500},
         'email': 'visheshsingh29537@gmail.com', 'telephone': '+919054349785',
         'location': {'@type': 'Place', 'address': address},
         'founder': {'@id': person_id}, 'sameAs': ['https://www.instagram.com/formiqbloom/']},
        {'@type': 'Person', '@id': person_id, 'name': 'Vishesh Singh', 'jobTitle': 'Founder',
         'url': 'https://visheshsingh.vercel.app/', 'worksFor': {'@id': org_id}},
        {'@type': 'WebSite', '@id': origin + '/#website', 'url': origin + '/', 'name': 'FormiqBloom',
         'inLanguage': 'en', 'publisher': {'@id': org_id}}
    ]


def page_graph(page, origin, image):
    canonical = origin + page['path']
    graph = business_graph(origin)
    entity = {'@type': page['type'], '@id': canonical + '#webpage', 'url': canonical,
              'name': page['title'], 'description': page['description'], 'inLanguage': 'en',
              'isPartOf': {'@id': origin + '/#website'}, 'about': {'@id': origin + '/#organization'},
              'primaryImageOfPage': {'@type': 'ImageObject', 'url': image, 'width': 1200, 'height': 630}}
    if page['path'] != '/':
        entity['breadcrumb'] = {'@id': canonical + '#breadcrumb'}
        graph.append({'@type': 'BreadcrumbList', '@id': canonical + '#breadcrumb', 'itemListElement': [
            {'@type': 'ListItem', 'position': 1, 'name': 'Home', 'item': origin + '/'},
            {'@type': 'ListItem', 'position': 2, 'name': page['name'], 'item': canonical}
        ]})
    if page['path'] == '/team':
        entity['mainEntity'] = {'@id': origin + '/#founder'}
    if page['path'] == '/work':
        projects = [
            {'@type': 'WebApplication', '@id': canonical + '#micromuse', 'name': 'MicroMuse',
             'url': 'https://micromuse.vercel.app/', 'creator': {'@id': origin + '/#founder'},
             'description': 'AI-assisted nutrition tracking with meal logging, progress dashboards, and a responsive web and PWA experience.'},
            {'@type': 'WebApplication', '@id': canonical + '#relaychatting', 'name': 'RelayChatting',
             'url': 'https://relaychatting.vercel.app/', 'creator': {'@id': origin + '/#founder'},
             'description': 'A live text messaging web application with usernames and user accounts.'}
        ]
        graph.extend(projects)
        graph.append({'@type': 'ItemList', '@id': canonical + '#projects', 'name': 'Selected work',
                      'itemListElement': [{'@type': 'ListItem', 'position': i, 'item': {'@id': project['@id']}}
                                          for i, project in enumerate(projects, 1)]})
        entity['mainEntity'] = {'@id': canonical + '#projects'}
    if page['path'] == '/':
        for name, slug, description in [
            ('Website Design & Development', 'websites', 'Responsive business websites with clear navigation and enquiry flows.'),
            ('Managed Hosting & Maintenance', 'hosting', 'Deployment, HTTPS, monitoring, and ongoing updates within an agreed support plan.'),
            ('AI Assistants', 'assistants', 'Assistants grounded in approved business information that answer FAQs and guide enquiries.')
        ]:
            graph.append({'@type': 'Service', '@id': origin + '/#service-' + slug, 'name': name,
                          'description': description, 'url': origin + '/#' + slug,
                          'provider': {'@id': origin + '/#organization'}})
    graph.append(entity)
    return {'@context': 'https://schema.org', '@graph': graph}


def metadata(page, origin, social_path):
    escape = lambda value: html.escape(value, quote=True)
    canonical, image = origin + page['path'], origin + social_path
    tags = [START, '  <title>' + escape(page['title']) + '</title>',
            '  <meta name="description" content="' + escape(page['description']) + '">',
            '  <link rel="canonical" href="' + escape(canonical) + '">',
            '  <meta name="robots" content="index, follow, max-image-preview:large">',
            '  <meta name="author" content="FormiqBloom">']
    properties = {'og:type': 'website', 'og:site_name': 'FormiqBloom', 'og:locale': 'en_IN',
                  'og:title': page['title'], 'og:description': page['description'], 'og:url': canonical,
                  'og:image': image, 'og:image:type': 'image/png', 'og:image:width': '1200',
                  'og:image:height': '630', 'og:image:alt': 'FormiqBloom — websites, hosting, and AI assistants. Based in Surat.'}
    tags.extend('  <meta property="' + key + '" content="' + escape(value) + '">' for key, value in properties.items())
    twitter = {'twitter:card': 'summary_large_image', 'twitter:title': page['title'],
               'twitter:description': page['description'], 'twitter:image': image,
               'twitter:image:alt': properties['og:image:alt']}
    tags.extend('  <meta name="' + key + '" content="' + escape(value) + '">' for key, value in twitter.items())
    schema = json.dumps(page_graph(page, origin, image), ensure_ascii=False, indent=2).replace('<', '\\u003c')
    tags.extend(['  <script type="application/ld+json">', schema, '  </script>', END])
    return '\n'.join(tags)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--site-url', help='Set the production HTTPS origin, e.g. https://your-domain.in')
    args = parser.parse_args()
    config_path = ROOT / 'seo.config.json'
    config = json.loads(config_path.read_text())
    old_origin = config['site_url'].rstrip('/')
    origin = (args.site_url or old_origin).rstrip('/')
    parsed = urlsplit(origin)
    if parsed.scheme != 'https' or not parsed.hostname or parsed.path or parsed.query or parsed.fragment or parsed.username or parsed.password:
        parser.error('Use a bare HTTPS origin without a path, query, or credentials.')
    config['site_url'] = origin
    output = {}
    for page in config['pages']:
        path = ROOT / page['file']
        source = path.read_text()
        block = metadata(page, origin, config['social_image'])
        if START in source:
            pattern = re.escape(START) + r'.*?' + re.escape(END)
            source, count = re.subn(pattern, lambda _: block, source, flags=re.S)
        else:
            source, descriptions = re.subn(r'  <meta name="description"[^>]*>\n', '', source)
            source, count = re.subn(r'  <title>.*?</title>', lambda _: block, source)
            if descriptions != 1:
                raise ValueError('Expected one original description in ' + page['file'])
        if count != 1:
            raise ValueError('Expected one SEO block in ' + page['file'])
        # Also migrate absolute home/logo links when the production domain changes.
        if old_origin != origin:
            source = source.replace(old_origin + '/', origin + '/')
        output[path] = source
    namespace = 'http://www.sitemaps.org/schemas/sitemap/0.9'
    ET.register_namespace('', namespace)
    sitemap = ET.Element('{' + namespace + '}urlset')
    for page in config['pages']:
        item = ET.SubElement(sitemap, '{' + namespace + '}url')
        ET.SubElement(item, '{' + namespace + '}loc').text = origin + page['path']
    ET.indent(sitemap, space='  ')
    output[ROOT / 'sitemap.xml'] = '<?xml version="1.0" encoding="UTF-8"?>\n' + ET.tostring(sitemap, encoding='unicode') + '\n'
    output[ROOT / 'robots.txt'] = 'User-agent: *\nAllow: /\n\nSitemap: ' + origin + '/sitemap.xml\n'
    output[config_path] = json.dumps(config, ensure_ascii=False, indent=2) + '\n'
    for path, content in output.items():
        path.write_text(content)
    print('Updated SEO for ' + str(len(config['pages'])) + ' pages at ' + origin + ' (no build required).')


if __name__ == '__main__':
    main()
