def metadata(page, origin, social_path):
    escape = lambda value: html.escape(value, quote=True)
    canonical, image = origin + page['path'], origin + social_path
    tags = [START, '  <title>' + escape(page['title']) + '</title>',
            '  <meta name="description" content="' + escape(page['description']) + '">',
            '  <link rel="canonical" href="' + escape(canonical) + '">',
            '  <meta name="robots" content="index, follow, max-image-preview:large">',
            '  <meta name="author" content="FormiqBloom">']
    properties = {'og:type': 'article' if page.get('article') else 'website', 'og:site_name': 'FormiqBloom', 'og:locale': 'en_IN',
                  'og:title': page['title'], 'og:description': page['description'], 'og:url': canonical,
                  'og:image': image, 'og:image:type': 'image/png', 'og:image:width': '1200',
                  'og:image:height': '630', 'og:image:alt': 'FormiqBloom — websites, hosting, and AI assistants. Based in Surat.'}
    if page.get('article'):
        properties.update({'article:published_time': page['article']['date_published'],
                           'article:modified_time': page['article']['date_modified'],
                           'article:section': page['article']['category']})
    tags.extend('  <meta property="' + key + '" content="' + escape(value) + '">' for key, value in properties.items())
    twitter = {'twitter:card': 'summary_large_image', 'twitter:title': page['title'],
               'twitter:description': page['description'], 'twitter:image': image,
               'twitter:image:alt': properties['og:image:alt']}
    tags.extend('  <meta name="' + key + '" content="' + escape(value) + '">' for key, value in twitter.items())
    schema = json.dumps(page_graph(page, origin, image), ensure_ascii=False, indent=2).replace('<', '\\u003c')
    tags.extend(['  <script type="application/ld+json">', schema, '  </script>', END])
    return '\n'.join(tags)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--site-url', help='Set the production HTTPS origin, e.g. https://your-domain.in')
    args = parser.parse_args()
    config_path = ROOT / 'seo.config.json'
    config = json.loads(config_path.read_text())
    old_origin = config['site_url'].rstrip('/')
    origin = (args.site_url or old_origin).rstrip('/')
    parsed = urlsplit(origin)
    if parsed.scheme != 'https' or not parsed.hostname or parsed.path or parsed.query or parsed.fragment or parsed.username or parsed.password:
        parser.error('Use a bare HTTPS origin without a path, query, or credentials.')
    config['site_url'] = origin
    output = {}
    for page in config['pages']:
        path = ROOT / page['file']
        source = path.read_text()
        metadata_page = dict(page)
        if page.get('pricing_page'):
            metadata_page['website_tiers'] = next(item['website_tiers'] for item in config['pages'] if item['path'] == '/')
        block = metadata(metadata_page, origin, config['social_image'])
        if START in source:
            pattern = re.escape(START) + r'.*?' + re.escape(END)
            source, count = re.subn(pattern, lambda _: block, source, flags=re.S)
        else:
            source, descriptions = re.subn(r'  <meta name="description"[^>]*>\n', '', source)
            source, count = re.subn(r'  <title>.*?</title>', lambda _: block, source)
            if descriptions != 1:
                raise ValueError('Expected one original description in ' + page['file'])
        if count != 1:
            raise ValueError('Expected one SEO block in ' + page['file'])
        # Also migrate absolute home/logo links when the production domain changes.
        if old_origin != origin:
            source = source.replace(old_origin + '/', origin + '/')
        output[path] = source
    namespace = 'http://www.sitemaps.org/schemas/sitemap/0.9'
    ET.register_namespace('', namespace)
    sitemap = ET.Element('{' + namespace + '}urlset')
    for page in config['pages']:
        item = ET.SubElement(sitemap, '{' + namespace + '}url')
        ET.SubElement(item, '{' + namespace + '}loc').text = origin + page['path']
    ET.indent(sitemap, space='  ')
    output[ROOT / 'sitemap.xml'] = '<?xml version="1.0" encoding="UTF-8"?>\n' + ET.tostring(sitemap, encoding='unicode') + '\n'
    output[ROOT / 'robots.txt'] = 'User-agent: *\nAllow: /\n\nSitemap: ' + origin + '/sitemap.xml\n'
    output[config_path] = json.dumps(config, ensure_ascii=False, indent=2) + '\n'
    for path, content in output.items():
        path.write_text(content)
    print('Updated SEO for ' + str(len(config['pages'])) + ' pages at ' + origin + ' (no build required).')


if __name__ == '__main__':
    main()
